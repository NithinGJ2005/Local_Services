-- Aguntaka Pahachana Kendra - Local Services Staff Dashboard Database Schema
-- Pure MySQL for XAMPP (MariaDB / MySQL 5.7+)

CREATE DATABASE IF NOT EXISTS `aguntaka_local_services` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `aguntaka_local_services`;

-- 1. Staff Users Table
CREATE TABLE IF NOT EXISTS `staff_users` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `username` VARCHAR(50) UNIQUE NOT NULL,
    `name` VARCHAR(100) NOT NULL,
    `email` VARCHAR(100) UNIQUE NOT NULL,
    `password_hash` VARCHAR(255) NOT NULL,
    `role` ENUM('staff', 'supervisor', 'admin') DEFAULT 'staff',
    `is_active` TINYINT(1) DEFAULT 1,
    `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. Local Services Table
CREATE TABLE IF NOT EXISTS `local_services` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `service_name` VARCHAR(150) NOT NULL,
    `category` VARCHAR(60) NOT NULL,
    `short_description` VARCHAR(255) NULL,
    `description` TEXT NULL,
    `file_url` VARCHAR(255) NULL,
    `file_name` VARCHAR(255) NULL,
    `file_type` VARCHAR(100) NULL,
    `phone` VARCHAR(25) NOT NULL,
    `alternate_phone` VARCHAR(25) NULL,
    `email` VARCHAR(100) NULL,
    `website` VARCHAR(255) NULL,
    `contact_person` VARCHAR(100) NULL,
    `address_line` VARCHAR(255) NOT NULL,
    `locality` VARCHAR(100) NOT NULL,
    `city` VARCHAR(100) NOT NULL,
    `district` VARCHAR(100) NOT NULL,
    `state` VARCHAR(100) DEFAULT 'Karnataka',
    `pincode` VARCHAR(10) NULL,
    `latitude` DECIMAL(10, 7) NULL,
    `longitude` DECIMAL(10, 7) NULL,
    `opening_time` TIME NULL,
    `closing_time` TIME NULL,
    `working_days` VARCHAR(100) NULL,
    `is_24_hours` TINYINT(1) DEFAULT 0,
    `availability_notes` TEXT NULL,
    `facilities` TEXT NULL,
    `accessibility_notes` TEXT NULL,
    `public_notes` TEXT NULL,
    `internal_notes` TEXT NULL,
    `status` ENUM('Draft', 'Published', 'Inactive', 'Archived') DEFAULT 'Draft',
    `created_by` INT NULL,
    `updated_by` INT NULL,
    `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `published_at` DATETIME NULL,
    INDEX `idx_category` (`category`),
    INDEX `idx_status` (`status`),
    INDEX `idx_city` (`city`),
    INDEX `idx_district` (`district`),
    INDEX `idx_coords` (`latitude`, `longitude`),
    CONSTRAINT `fk_service_creator` FOREIGN KEY (`created_by`) REFERENCES `staff_users` (`id`) ON DELETE SET NULL,
    CONSTRAINT `fk_service_updater` FOREIGN KEY (`updated_by`) REFERENCES `staff_users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;



